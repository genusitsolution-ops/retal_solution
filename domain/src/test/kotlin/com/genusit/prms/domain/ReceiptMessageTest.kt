package com.genusit.prms.domain

import com.genusit.prms.domain.model.Receipt
import com.genusit.prms.domain.model.ReceiptLine
import com.genusit.prms.domain.util.ReceiptLabels
import com.genusit.prms.domain.util.ReceiptMessage
import java.net.URLDecoder
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

/** Uses the receipt from the 25 Oct 2026 screenshot and the app's real EN / HI / MR labels. */
class ReceiptMessageTest {
    private val receipt = Receipt(
        receiptNumber = "OC-20261025142859-5AFA", date = "2026-10-25 14:28:59", amount = 50.0, mode = "cash",
        modeLabel = "Cash", remarks = "hh", tenantName = "Tenant1", tenantPhone = "98765 43210",
        propertyCode = "r1", city = "pune", ownerName = "abhi gupta", collectedBy = "मालमत्ता मालक",
        lines = listOf(ReceiptLine(1, "INV-202606-0001-EE666", "मे 2026", 3269.0, 50.0, 800.0)),
    )

    private val en = ReceiptLabels("Rent payment receipt", "Receipt no.", "Date", "Received from", "Property", "Amount paid",
        "Payment mode", "Reference", "Collected by", "Remarks", "Bill total", "This payment", "Balance now",
        "Thank you! Receipt generated by Rental Solution.")
    private val hi = ReceiptLabels("किराया भुगतान रसीद", "रसीद नं.", "तिथि", "किससे प्राप्त", "संपत्ति", "भुगतान की गई राशि",
        "भुगतान माध्यम", "संदर्भ", "वसूलकर्ता", "टिप्पणी", "बिल कुल", "यह भुगतान", "अब शेष",
        "धन्यवाद! यह रसीद रेंटल सॉल्यूशन द्वारा बनाई गई है।")
    private val mr = ReceiptLabels("भाडे भरणा पावती", "पावती क्र.", "तारीख", "यांच्याकडून मिळाले", "मालमत्ता", "भरलेली रक्कम",
        "भरणा माध्यम", "संदर्भ", "वसूल करणारे", "शेरा", "बिल एकूण", "हा भरणा", "आता शिल्लक",
        "धन्यवाद! ही पावती रेंटल सोल्यूशनद्वारे तयार केली आहे.")

    @Test fun englishMessage() {
        val t = ReceiptMessage.text(receipt, en, "25 October 2026", "Cash")
        assertTrue("Receipt no.: OC-20261025142859-5AFA" in t)
        assertTrue("Amount paid: *₹50.00*" in t)
        assertTrue("Balance now: ₹800.00" in t)
        assertTrue("Received from: Tenant1" in t && "Property: r1, pune" in t && "Remarks: hh" in t)
    }

    @Test fun hindiMessage() {
        val t = ReceiptMessage.text(receipt, hi, "25 अक्टूबर 2026", "नकद")
        assertTrue("रसीद नं.: OC-20261025142859-5AFA" in t)
        assertTrue("भुगतान माध्यम: नकद" in t && "अब शेष: ₹800.00" in t && "तिथि: 25 अक्टूबर 2026" in t)
        assertFalse("Receipt no." in t || "Balance now" in t, "no English labels")
    }

    @Test fun marathiMessage() {
        val t = ReceiptMessage.text(receipt, mr, "25 ऑक्टोबर 2026", "रोख")
        assertTrue(t.startsWith("*abhi gupta*\nभाडे भरणा पावती"))
        assertTrue("पावती क्र.: OC-20261025142859-5AFA" in t && "भरलेली रक्कम: *₹50.00*" in t)
        assertTrue("बिल एकूण: ₹3,269.00" in t && "हा भरणा: ₹50.00" in t && "आता शिल्लक: ₹800.00" in t)
        assertFalse("Receipt no." in t || "Amount paid" in t, "no English labels")
    }

    @Test fun whatsAppLinkKeepsUnicode() {
        val t = ReceiptMessage.text(receipt, mr, "25 ऑक्टोबर 2026", "रोख")
        val url = ReceiptMessage.whatsAppUrl(receipt.tenantPhone, t)!!
        assertTrue(url.startsWith("https://wa.me/919876543210?text="))
        assertFalse(url.contains(' ') || url.contains('+'), "spaces encoded as %20")
        assertEquals(t, URLDecoder.decode(url.substringAfter("text="), "UTF-8"), "round-trips exactly")
    }

    @Test fun phoneNormalization() {
        assertEquals("919876543210", ReceiptMessage.normalizeIndianMobile("+91-98765-43210"))
        assertEquals("919876543210", ReceiptMessage.normalizeIndianMobile("09876543210"))
        assertNull(ReceiptMessage.normalizeIndianMobile(null))
        assertNull(ReceiptMessage.normalizeIndianMobile("12345"))
        assertNull(ReceiptMessage.whatsAppUrl("", "x"), "no number → share sheet")
    }
}
