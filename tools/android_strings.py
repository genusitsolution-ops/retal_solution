    for k, v in S.items():
        txt = v[i]
        fmt = re.findall(r'%\d\$[sd]', v[0])
        assert sorted(fmt) == sorted(re.findall(r'%\d\$[sd]', txt)), (lang, k)
        attr = '' if fmt else ''
        out.append(f'    <string name="{k}"{attr}>{esc(txt)}</string>')
    out.append('    <string-array name="months">' + ''.join(f'<item>{m}</item>' for m in MONTHS[lang]) + '</string-array>')
    out.append('</resources>')
    os.makedirs(f"{base}/{folder}", exist_ok=True)
    open(f"{base}/{folder}/strings.xml", "w", encoding="utf-8").write("\n".join(out) + "\n")
