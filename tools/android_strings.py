import re, os, sys
from xml.sax.saxutils import escape
def esc(t):
    t = escape(t)
    t = t.replace("'", "\\'").replace('"', '\\"')
    if t.startswith('@') or t.startswith('?'): t = '\\' + t
    return t
base = sys.argv[1]
used = set(sys.argv[2].split()) if len(sys.argv) > 2 else set()
for i, (lang, folder) in enumerate([("en", "values"), ("hi", "values-hi"), ("mr", "values-mr")]):
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    if lang == "en": pass
    for k, v in S.items():
        txt = v[i]
        fmt = re.findall(r'%\d\$[sd]', v[0])
        assert sorted(fmt) == sorted(re.findall(r'%\d\$[sd]', txt)), (lang, k)
        attr = '' if fmt else ''
        out.append(f'    <string name="{k}"{attr}>{esc(txt)}</string>')
    out.append('    <string-array name="months">' + ''.join(f'<item>{m}</item>' for m in MONTHS[lang]) + '</string-array>')
    out.append('</resources>')
    os.makedirs(f"{base}/{folder}", exist_ok=True)
    open(f"{base}/{folder}/strings.xml", "w", encoding="utf-8").write("\n".join(out) + "\n")
missing = used - set(S) - {"months"}
